# Declare variables
x = 5
y = 10

# Python expressions return True/False. int() converts them to 1/0 to match C output.
print("x > y :-", int(x > y))   # Greater than
print("x < y :-", int(x < y))   # Less than
print("x == y :-", int(x == y)) # Equal to
print("x != y :-", int(x != y)) # Not equal to
print("x >= y :-", int(x >= y)) # Greater than or equal to
print("x <= y :-", int(x <= y)) # Less than or equal to
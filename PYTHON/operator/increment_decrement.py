# Initialize variable
a = 5

# Pre-increment simulation
a += 1
print(f"Pre-increment (++a): {a}")

# Post-increment simulation
print(f"Post-increment (a++): {a}")
a += 1

# Pre-decrement simulation
a -= 1
print(f"Pre-decrement (--a): {a}")

# Post-decrement simulation
print(f"Post-decrement (a--): {a}")
a -= 1

# Final value of a
print(f"Final value of a => {a}")
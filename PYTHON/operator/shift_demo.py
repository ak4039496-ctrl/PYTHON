# Input a number
num = int(input("Enter a number:- "))

# Left shift operator (multiply by 2 for each shift)
print("num << 1 =", num << 1)   # Shift left by 1 bit
print("num << 2 =", num << 2)   # Shift left by 2 bits

# Right shift operator (divide by 2 for each shift)
print("num >> 1 =", num >> 1)   # Shift right by 1 bit
print("num >> 2 =", num >> 2)   # Shift right by 2 bits
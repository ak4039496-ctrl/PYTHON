# Description:- Program to check whether a number is even or odd.

# Input from user
num = int(input("Enter a number:- "))

# If condition to check even number
if num % 2 == 0:
    print(f"{num} is Even")
# Else condition for odd number
else:
    print(f"{num} is Odd")
    